  /**
   * Helper to get grammar list for array of selected units
   */
  static getGrammarForUnits(grade, selectedUnitsArray) {
    const gradeData = this.DATA[grade] || this.DATA[8];
    const grammarSet = new Set();

    selectedUnitsArray.forEach(unit => {
      if (gradeData[unit] && gradeData[unit].grammar) {
        gradeData[unit].grammar.forEach(g => grammarSet.add(g));
      }
    });

    return Array.from(grammarSet);
  }

  /**
   * Helper to get vocabulary list for array of selected units
   */
  static getVocabForUnits(grade, selectedUnitsArray) {
    const gradeData = this.DATA[grade] || this.DATA[8];
    const vocabSet = new Set();

    selectedUnitsArray.forEach(unit => {
      if (gradeData[unit] && gradeData[unit].vocab) {
        gradeData[unit].vocab.forEach(v => vocabSet.add(v));
      }
    });

    return Array.from(vocabSet);
  }
